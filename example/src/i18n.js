const STORAGE_KEY = "example-lang";
let current = (() => {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && saved in STRINGS) return saved;
  } catch {
    // storage unavailable: follow the browser
  }
  return navigator.language?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
})();
const listeners = new Set();

/** The current language: "en" or "zh-CN". */
export const lang = () => current;

/** The string for `key` in the current language, with `{name}` placeholders filled from `values`. */
export function t(key, values = {}) {
  const text = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (values[name] ?? "").toString());
}

/** Applies the current language to every marked element below `root`. */
export function applyI18n(root = document) {
  document.documentElement.lang = current;
  for (const el of root.querySelectorAll("[data-i18n]")) {
    if (el.tagName === "TITLE") document.title = t(el.dataset.i18n);
    else el.textContent = t(el.dataset.i18n);
  }
  for (const el of root.querySelectorAll("[data-i18n-attr]"))
    for (const pair of el.dataset.i18nAttr.split(";")) {
      const [attr, key] = pair.split(":");
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    }
}

/** Switches the language, remembers the choice and tells the listeners. */
export function setLang(next) {
  if (!(next in STRINGS) || next === current) return;
  current = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // storage unavailable: the choice lasts until the page is closed
  }
  applyI18n();
  for (const listener of listeners) listener(next);
}

/** Calls `listener(lang)` after every language switch. */
export function onLangChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}
