export function nameFor(id: string): string {
	const short = id.replace(/^minecraft:/, "");
	if (names[short]) return names[short];
	for (const [c, label] of Object.entries(colors))
		for (const [s, n] of Object.entries({
			stained_glass: "染色玻璃",
			stained_glass_pane: "染色玻璃板",
			wool: "羊毛",
			carpet: "地毯",
			concrete: "混凝土",
			terracotta: "陶瓦",
			shulker_box: "潜影盒",
			bed: "床",
			banner: "旗帜",
		}))
			if (short === `${c}_${s}`) return label + n;
	for (const [w, label] of Object.entries(woods))
		for (const [s, n] of Object.entries(suffixes)) {
			if (short === `${w}_${s}`) return label + n;
			if (short === `stripped_${w}_${s}`) return "去皮" + label + n;
		}
	return short.replaceAll("_", " ");
}
